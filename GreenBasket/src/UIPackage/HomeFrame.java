    private void cmbSearchCatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbSearchCatActionPerformed
        ProductManagerClass mgc=new ProductManagerClass();
        String Category = cmbSearchCat.getSelectedItem().toString();
        String tableTitle = """
                               ItemID \t ItemName \t Supplier \t\t Price \t StockQty 
                               --------------------------------------------------------------------------------------------------------------------------------------------
                               """;
        String result = mgc.searchCategory(Category);
        if(!result.isEmpty())
        {
            showArea.setText(tableTitle+result);
        }
        else
        {
            showArea.setText("Sorry, we could not find anything");
        }
    }//GEN-LAST:event_cmbSearchCatActionPerformed

