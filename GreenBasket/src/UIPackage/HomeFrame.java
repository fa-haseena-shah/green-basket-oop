    private void initialSetup()
    {
        System.out.println("Username: " + UserName + ", Role: " + Role);
        ProductManagerClass mgc=new ProductManagerClass();
        lblUserName.setText(UserName);
        lblRole.setText(Role);
        
        if (this.Role.equals("Sales Assistant")) 
        {
            btnCreateAcc.setVisible(false);
            btnMonitorInventory.setVisible(false);
        }
        
        String pTableTitle = """
                               ItemID \t ItemName \t Category \t Supplier \t Price \t StockQty
                               ----------------------------------------------------------------------------------------------------------
                               """;
        String ProductInfo = mgc.viewProducts();
        if(!ProductInfo.isEmpty())
        {
            showArea.setText(pTableTitle+ProductInfo);
        }
        else
        {
            showArea.setText("There are no products available for viewing at this time...");
        }
    }
